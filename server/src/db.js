export function databaseUrl() {
  const url = process.env.DATABASE_URL;
  if (!url) {
    throw new Error('DATABASE_URL is not set. Copy .env.example to .env and add your Postgres connection string.');
  }
  return url;
}

export function createDb({ connectionString = databaseUrl(), ssl = true, max = 20 } = {}) {
  const pool = new Pool({
    connectionString,
    ssl: ssl ? { rejectUnauthorized: false } : false,
    max,
    keepAlive: true,
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 15_000,
  });
  pool.on('error', (err) => console.error('[db] idle client error', err.message));

  const db = {
    pool,
    query: (text, params) => pool.query(text, params),
    one: async (text, params) => (await pool.query(text, params)).rows[0] ?? null,
    many: async (text, params) => (await pool.query(text, params)).rows,

    /** Run fn inside a transaction; fn receives the client and must use it for every query. */
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const out = await fn(client);
        await client.query('COMMIT');
        return out;
      } catch (err) {
        try { await client.query('ROLLBACK'); } catch { /* connection may be gone */ }
        throw err;
      } finally {
        client.release();
      }
    },

    async migrate() {
      await pool.query(SCHEMA);
      await pool.query('INSERT INTO settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING');
    },

    async ping() {
      const { rows } = await pool.query('SELECT current_database() AS db, now() AS at');
      return rows[0];
    },

    close: () => pool.end(),

    nextNumber: (client, kind, date, prefix) => nextNumber(client, kind, date, prefix),
    recomputeDocumentTotals: (client, table, id) => recomputeDocumentTotals(client, table, id),
    allocatePayment: (client, paymentId, allocations) => allocatePayment(client, paymentId, allocations),
  };

  return db;
}

/**
 * Atomically reserve the next document number for a kind + year.
 * `INSERT … ON CONFLICT DO UPDATE … RETURNING` serialises concurrent writers.
 */
export async function nextNumber(client, kind, date, prefix) {
  const year = String(date).slice(0, 4);
  const key = `${kind}:${year}`;
  const { rows } = await client.query(
    `INSERT INTO counters (key, value) VALUES ($1, 1)
     ON CONFLICT (key) DO UPDATE SET value = counters.value + 1
     RETURNING value`,
    [key],
  );
  const value = rows[0].value;
  return `${prefix}-${year}-${String(value).padStart(4, '0')}`;
}

const DOC = {
  invoices: { lines: 'invoice_lines', fk: 'invoice_id' },
  bills: { lines: 'bill_lines', fk: 'bill_id' },
};

/** Recompute a document's totals, paid amount and derived status from its lines and allocations. */
export async function recomputeDocumentTotals(client, table, id) {
  const meta = DOC[table];
  if (!meta) throw new Error(`Unknown document table: ${table}`);

  const { rows: docs } = await client.query(`SELECT * FROM ${table} WHERE id = $1`, [id]);
  const doc = docs[0];
  if (!doc) return null;

  const { rows: lines } = await client.query(
    `SELECT * FROM ${meta.lines} WHERE ${meta.fk} = $1 ORDER BY position, id`, [id],
  );
  const subtotal = lines.reduce((sum, line) => sum + line.amount_cents, 0);
  const tax = lines.reduce((sum, line) => sum + Math.round((line.amount_cents * line.tax_rate) / 100), 0);
  const total = subtotal - doc.discount_cents + tax;

  const { rows: paidRows } = await client.query(
    `SELECT COALESCE(SUM(amount_cents), 0)::int AS paid FROM allocations WHERE ${meta.fk} = $1`, [id],
  );
  const paid = paidRows[0].paid;

  let status = doc.status;
  if (status !== 'draft' && status !== 'void') {
    status = paid >= total && total > 0 ? 'paid' : paid > 0 ? 'partial' : 'open';
  }

  await client.query(
    `UPDATE ${table}
        SET subtotal_cents = $1, tax_cents = $2, total_cents = $3, paid_cents = $4,
            status = $5, updated_at = now()
      WHERE id = $6`,
    [subtotal, tax, total, paid, status, id],
  );
  return { subtotal, tax, total, paid, status };
}

/** Apply a payment to documents, enforcing contact match, draft/void guards and open balances. */
export async function allocatePayment(client, paymentId, allocations) {
  const { rows: paymentRows } = await client.query('SELECT * FROM payments WHERE id = $1', [paymentId]);
  const payment = paymentRows[0];
  if (!payment) throw new Error('Payment not found');

  for (const allocation of allocations) {
    const isInvoice = allocation.docType === 'invoice';
    const table = isInvoice ? 'invoices' : 'bills';
    const { rows } = await client.query(`SELECT * FROM ${table} WHERE id = $1`, [allocation.docId]);
    const doc = rows[0];
    if (!doc) throw new Error(`Document ${allocation.docId} not found`);
    if (doc.contact_id !== payment.contact_id) throw new Error('Allocation contact does not match payment contact');
    if (doc.status === 'void' || doc.status === 'draft') throw new Error(`Cannot allocate to a ${doc.status} document`);

    const balance = doc.total_cents - doc.paid_cents;
    if (allocation.amountCents <= 0) throw new Error('Allocation amount must be positive');
    if (allocation.amountCents > balance) throw new Error(`Allocation exceeds open balance of ${doc.number}`);

    await client.query(
      `INSERT INTO allocations (payment_id, ${isInvoice ? 'invoice_id' : 'bill_id'}, amount_cents)
       VALUES ($1, $2, $3)`,
      [paymentId, allocation.docId, allocation.amountCents],
    );
    await recomputeDocumentTotals(client, table, allocation.docId);
  }

  const { rows: sums } = await client.query(
    'SELECT COALESCE(SUM(amount_cents), 0)::int AS allocated FROM allocations WHERE payment_id = $1', [paymentId],
  );
  if (sums[0].allocated > payment.amount_cents) throw new Error('Allocations exceed payment amount');
  return sums[0].allocated;
}
