// Keep DATE as a plain 'YYYY-MM-DD' string and timestamps as ISO strings so the API
// contract stays identical to the previous SQLite build (no timezone surprises in JSON).
types.setTypeParser(1082, (value) => value);
types.setTypeParser(1114, (value) => value.replace(' ', 'T'));
types.setTypeParser(1184, (value) => new Date(value).toISOString());

